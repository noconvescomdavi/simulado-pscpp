import fs from "node:fs";
const targetPath="data/questions/legislacao-regulamentacao.json";
const packPath="data/question-extensions/normam-112-audited.json";
const bank=JSON.parse(fs.readFileSync(targetPath,"utf8"));
const pack=JSON.parse(fs.readFileSync(packPath,"utf8"));
const newQuestions=pack.questions||[];
if(newQuestions.length!==141)throw new Error("Pacote NORMAM-112 deve conter 141 questões");
if(new Set(newQuestions.map(q=>q.id)).size!==141)throw new Error("IDs duplicados no pacote NORMAM-112");
const uc={};
for(const q of newQuestions){
  const id=q.taxonomy?.subtopic_id; uc[id]=(uc[id]||0)+1;
  if(q.taxonomy?.subject_id!=="IV")throw new Error("subject_id inválido: "+q.id);
  if(q.taxonomy?.bibliography_id!=="normam112")throw new Error("bibliography_id inválido: "+q.id);
  if(!q.taxonomy?.chapter_id?.startsWith("normam112::"))throw new Error("chapter_id inválido: "+q.id);
  if(!Array.isArray(q.options)||q.options.length!==5)throw new Error("alternativas inválidas: "+q.id);
  if(!["A","B","C","D","E"].includes(q.correct_answer))throw new Error("gabarito inválido: "+q.id);
  if(q.active!==true)throw new Error("questão nova inativa: "+q.id);
}
if(Object.keys(uc).length!==47||Object.values(uc).some(v=>v!==3))throw new Error("Cobertura UC inválida");
const isN112=q=>String(q.module||"").includes("NORMAM-112")||(q.tags||[]).some(t=>String(t).toLowerCase().includes("n112"));
const legacy=bank.questions.filter(isN112);
if(legacy.some(q=>q.active!==false))throw new Error("Há NORMAM-112 legada ativa");
const kept=bank.questions.filter(q=>!isN112(q));
const ids=new Set(kept.map(q=>q.id));
if(newQuestions.some(q=>ids.has(q.id)))throw new Error("Colisão de IDs");
bank.questions=[...kept,...newQuestions];
if(bank.questions.length!==1398)throw new Error("Total final inesperado: "+bank.questions.length);
bank.validation||={};
bank.validation.total=bank.questions.length;
bank.validation.total_questions=bank.questions.length;
bank.validation.by_module||={};
bank.validation.by_module["NORMAM-112/DPC — cerimonial da Marinha Mercante"]=141;
bank.validation.source_distribution||={};
bank.validation.source_distribution["LEG-N112"]=141;
bank.validation.last_sync="2026-09-30T21:00:00-03:00";
bank.validation.normam112_audit={integrated_active:141,removed_legacy_quarantined:legacy.length,coverage_units:47,questions_per_unit:3,audit_result:"approved_after_corrections",bibliography_id:"normam112"};
fs.writeFileSync(targetPath,JSON.stringify(bank,null,2)+"\n");
console.log(JSON.stringify({removedLegacy:legacy.length,added:newQuestions.length,total:bank.questions.length,coverageUnits:Object.keys(uc).length}));
